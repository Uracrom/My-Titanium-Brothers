def build():
    convs = load_conversations()
    excerpts, owned, placed = load_own_words(convs)
    ov = load_overrides()
    topics = [build_topic(spec, ov.get('topics', {}).get(spec['key'], {}), convs, excerpts, owned) for spec in TOPICS]
    files = {}
    for t in topics:
        files.update(topic_files(t))
    sizes = dict((rel, len(text.encode('utf-8'))) for rel, text in files.items())
    files['subject-map/INDEX.txt'] = index_file(topics, placed, len(excerpts), sizes)
    files['subject-map.html'] = html_page(topics)
    data = dict(
        title='Subject map', notice='derived index, generated by keyword matching (some topics also hand-reviewed); originals unchanged. Dates are conversation start dates.',
        last_updated=LAST_UPDATED, site=SITE, builder='tools/build_subject_map.py', overrides=OVERRIDES,
        conversations_total=len(convs), messages_total=sum(len(c['msgs']) for c in convs),
        own_words_excerpts=len(excerpts), own_words_excerpts_located=placed,
        files=sorted(files.keys()) + ['subject-map.json'],
        topics=topics)
    files['subject-map.json'] = json.dumps(data, ensure_ascii=False, indent=1, sort_keys=False) + '\n'
    return files


def main(argv):
    files = build()
    if '--check' in argv:
        bad = []
        for rel, text in sorted(files.items()):
            path = os.path.join(ROOT, rel)
            if not os.path.isfile(path) or open(path, encoding='utf-8').read() != text:
                bad.append(rel)
        folder = os.path.join(ROOT, 'subject-map')
        extra = sorted('subject-map/' + n for n in os.listdir(folder)) if os.path.isdir(folder) else []
        extra = [x for x in extra if x not in files]
        for rel in bad:
            print('differs from a fresh build: ' + rel)
        for rel in extra:
            print('not produced by the builder: ' + rel)
        return 1 if bad or extra else 0
    os.makedirs(os.path.join(ROOT, 'subject-map'), exist_ok=True)
    for name in os.listdir(os.path.join(ROOT, 'subject-map')):
        if name.endswith('.txt') and 'subject-map/' + name not in files:
            os.remove(os.path.join(ROOT, 'subject-map', name))
    for rel, text in files.items():
        with open(os.path.join(ROOT, rel), 'w', encoding='utf-8') as handle:
            handle.write(text)
    print('wrote %d files' % len(files))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
