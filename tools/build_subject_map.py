def load_conversations():
    convs = []
    for coll in COLLECTIONS:
        folder = os.path.join(ROOT, 'structured', coll)
        for name in sorted(os.listdir(folder)):
            if not name.endswith('.txt'):
                continue
            rel = 'structured/%s/%s' % (coll, name)
            text = read(rel)
            hdr = {}
            for line in text.split('\n', 14)[:13]:
                m = re.match(r'^([A-Z_]+): (.*)$', line)
                if m:
                    hdr[m.group(1)] = m.group(2)
            msgs = {}
            order = []
            for m in re.finditer(r'----- BEGIN MESSAGE (\S+) -----\n(.*?)\n----- END MESSAGE \1 -----', text, re.S):
                body = m.group(2)
                head, content = body.split('\nCONTENT:\n', 1)
                content = content.rsplit('\nEND CONTENT', 1)[0]
                fields = {}
                for line in head.split('\n'):
                    if ': ' in line:
                        k, v = line.split(': ', 1)
                        fields.setdefault(k, v)
                own = []
                inside = False
                for line in content.split('\n'):
                    if line == 'EMBEDDED MATERIAL:':
                        inside = True
                        continue
                    if line == 'END EMBEDDED MATERIAL':
                        inside = False
                        continue
                    if not inside:
                        own.append(line)
                mid = fields['MESSAGE']
                if mid not in msgs:
                    msgs[mid] = dict(id=mid, speaker=fields.get('SPEAKER', ''), kind=fields.get('SPEAKER_KIND', ''),
                                     src=fields.get('SOURCE_ARTICLE', ''), own='')
                    order.append(mid)
                msgs[mid]['own'] += '\n'.join(own) + '\n'
            convs.append(dict(id=hdr['CONVERSATION'], title=hdr.get('TITLE', ''), ai=hdr.get('COLLECTION', ''),
                              date=hdr.get('DATE', ''), file=rel, bytes=os.path.getsize(os.path.join(ROOT, rel)), msgs=[msgs[k] for k in order]))
    convs.sort(key=lambda c: (c['date'], c['id']))
    return convs


def load_own_words(convs):
    """Excerpts of the conservative own-words page, mapped to the Alex messages that contain them."""
    page = read('full-text/alex.html')
    excerpts = []
    for m in re.finditer(r'<article id="([^"]+)">(.*?)</article>', page, re.S):
        pre = re.search(r'<pre>(.*?)</pre>', m.group(2), re.S)
        if pre:
            excerpts.append(html.unescape(pre.group(1)))
    norm = lambda s: re.sub(r'\s+', ' ', s).strip()
    keys, chunks, pos = [], [], 0
    for ci, c in enumerate(convs):
        for mi, msg in enumerate(c['msgs']):
            if msg['speaker'] != 'ALEX':
                continue
            s = norm(msg['own'])
            keys.append((pos, ci, mi))
            chunks.append(s)
            pos += len(s) + 3
    big = ' \x00 '.join(chunks)
    starts = [k[0] for k in keys]
    owned = {}
    placed = 0

    def place(q, idx):
        j = big.find(q)
        hit = False
        while j != -1:
            k = bisect.bisect_right(starts, j) - 1
            owned.setdefault((keys[k][1], keys[k][2]), []).append(idx)
            hit = True
            j = big.find(q, j + 1)
        return hit

    for idx, text in enumerate(excerpts):
        q = norm(text)
        if not q:
            continue
        if place(q, idx):
            placed += 1
            continue
        parts = sorted((norm(x) for x in re.split(r'\n|\[…\]|…', text)), key=len, reverse=True)
        for part in parts[:3]:
            if len(part) < 30:
                break
            if place(part, idx):
                placed += 1
                break
    for key in owned:
        owned[key] = sorted(set(owned[key]))
    return excerpts, owned, placed


