# ---------------------------------------------------------------- matching
class Topic(object):
    def __init__(self, spec, ov):
        self.spec = spec
        self.ov = ov
        self.re = re.compile(spec['pattern'])
        rules = list(spec['exclusions']) + [item['regex'] for item in ov.get('pattern_exclusions', [])]
        self.ex = [re.compile(x) for x in rules]
        self.raw = re.compile(spec['raw']) if spec.get('raw') else None
        self.drop_msgs = {item['message'] for item in ov.get('exclude_messages', [])}
        self.drop_convs = {item['conversation'] for item in ov.get('exclude_conversations', [])}
        self.checked_convs = set(ov.get('reviewed_conversations', []))
        self.checked_msgs = set(ov.get('reviewed_messages', []))

    def find(self, text):
        s = blank_urls(text)
        bad = []
        for e in self.ex:
            bad.extend((m.start(), m.end()) for m in e.finditer(s))
        keep, dropped = [], 0
        for m in self.re.finditer(s):
            if any(a <= m.start() < b or a < m.end() <= b for a, b in bad):
                dropped += 1
            else:
                keep.append((m.start(), m.end()))
        return keep, dropped


def quote_from(text, start, end, maxw=25):
    ls = text.rfind('\n', 0, start) + 1
    le = text.find('\n', end)
    le = len(text) if le == -1 else le
    line = text[ls:le]
    s, e = start - ls, end - ls
    toks = [(m.start(), m.end()) for m in re.finditer(r'\S+', line)]
    hit = [i for i, (a, b) in enumerate(toks) if b > s and a < e]
    i0, i1 = hit[0], hit[-1]
    lo = i0
    while lo > 0 and i0 - lo < 10 and not SENT.search(line[toks[lo - 1][0]:toks[lo - 1][1]]):
        lo -= 1
    hi = min(lo + maxw - 1, len(toks) - 1)
    if hi < i1:
        lo = max(0, i1 - maxw + 1)
        hi = min(lo + maxw - 1, len(toks) - 1)
    for j in range(i1, hi + 1):
        if SENT.search(line[toks[j][0]:toks[j][1]]) and (j - lo + 1 >= 8 or j == hi):
            hi = j
            break
    return line[toks[lo][0]:toks[hi][1]], lo > 0, hi < len(toks) - 1, hi - lo + 1


def build_topic(spec, ov, convs, excerpts, owned):
    t = Topic(spec, ov)
    rows = []
    excluded_matches = 0
    raw_msgs = 0
    removed_msgs = 0
    first_any = None
    alex_quotes = []
    for ci, c in enumerate(convs):
        if c['id'] in t.drop_convs:
            continue
        r = dict(id=c['id'], title=c['title'], date=c['date'], ai=c['ai'], text=SITE + c['file'], text_bytes=c['bytes'],
                 archive=None, archive_bytes=None, messages=0, alex_own_words=0, alex_labeled=0, ai_messages=0, occurrences=0,
                 hand_checked=c['id'] in t.checked_convs, message_ids=[])
        for mi, msg in enumerate(c['msgs']):
            if msg['kind'] not in ('HUMAN', 'AI'):
                continue
            if t.raw and t.raw.search(blank_urls(msg['own'])):
                raw_msgs += 1
            keep, dropped = t.find(msg['own'])
            excluded_matches += dropped
            if not keep:
                continue
            if msg['id'] in t.drop_msgs:
                removed_msgs += 1
                continue
            r['occurrences'] += len(keep)
            r['message_ids'].append(msg['id'])
            if r['archive'] is None:
                r['archive'] = SITE + msg['src']
                r['archive_bytes'] = size_of(msg['src'])
            if first_any is None:
                first_any = dict(date=c['date'], ai=c['ai'], conversation=c['id'], message=msg['id'],
                                 speaker=msg['speaker'], archive=SITE + msg['src'], archive_bytes=size_of(msg['src']),
                                 text=SITE + c['file'], text_bytes=c['bytes'])
            if msg['kind'] == 'AI':
                r['ai_messages'] += 1
                continue
            r['alex_labeled'] += 1
            got = False
            for idx in owned.get((ci, mi), ()):
                found, _ = t.find(excerpts[idx])
                if not found:
                    continue
                if not got:
                    q, cut_before, cut_after, words = quote_from(excerpts[idx], *found[0])
                    if q in msg['own']:
                        alex_quotes.append(dict(date=c['date'], ai=c['ai'], conversation=c['id'], title=c['title'],
                                                message=msg['id'], quote=q, cut_before=cut_before, cut_after=cut_after,
                                                words=words, archive=SITE + msg['src'], archive_bytes=size_of(msg['src']),
                                                text=SITE + c['file'], text_bytes=c['bytes'],
                                                hand_checked=msg['id'] in t.checked_msgs))
                got = True
            if got:
                r['alex_own_words'] += 1
        r['messages'] = r['alex_labeled'] + r['ai_messages']
        if r['messages']:
            rows.append(r)
    rank = lambda r: (-r['messages'], -r['alex_own_words'], r['date'], r['id'])
    by_ai = {}
    for ai in AIS:
        mine = [r for r in rows if r['ai'] == ai]
        by_ai[ai] = dict(conversations=len(mine),
                         conversations_in_collection=sum(1 for c in convs if c['ai'] == ai),
                         messages=sum(r['messages'] for r in mine),
                         alex_own_words=sum(r['alex_own_words'] for r in mine),
                         alex_labeled=sum(r['alex_labeled'] for r in mine),
                         ai_messages=sum(r['ai_messages'] for r in mine),
                         top=[r['id'] for r in sorted(mine, key=rank)[:5]])
    first_by_ai = {}
    for q in alex_quotes:
        first_by_ai.setdefault(q['ai'], q)
    months = {}
    for r in rows:
        months[r['date'][:7]] = months.get(r['date'][:7], 0) + 1
    corrections = (len(ov.get('pattern_exclusions', [])), len(ov.get('exclude_messages', [])),
                   len(ov.get('exclude_conversations', [])))
    return dict(
        key=spec['key'], label=spec['label'], method=METHOD_SHORT[spec['method']],
        notice=METHOD_LABEL[spec['method']] + '. ' + BANNER_TAIL,
        description=spec['description'], pattern=spec['pattern'],
        exclusions=list(spec['exclusions']),
        override_rules=[dict(item) for item in ov.get('pattern_exclusions', [])],
        note=ov.get('note', ''),
        totals=dict(conversations=len(rows), messages=sum(r['messages'] for r in rows),
                    alex_own_words=sum(r['alex_own_words'] for r in rows),
                    conversations_with_alex_own_words=sum(1 for r in rows if r['alex_own_words']),
                    alex_labeled=sum(r['alex_labeled'] for r in rows),
                    ai_messages=sum(r['ai_messages'] for r in rows),
                    occurrences=sum(r['occurrences'] for r in rows),
                    hand_checked_conversations=sum(1 for r in rows if r['hand_checked'])),
        removals=dict(matches_removed_by_rules=excluded_matches, messages_removed_by_hand=removed_msgs,
                      conversations_removed_by_hand=len([c for c in convs if c['id'] in t.drop_convs]),
                      override_rules=corrections[0], override_messages=corrections[1],
                      override_conversations=corrections[2]),
        plain_word_messages=raw_msgs if t.raw else None,
        first_match_any_speaker=first_any,
        first_in_alex_own_words=alex_quotes[0] if alex_quotes else None,
        alex_first_mention_by_ai=sorted(first_by_ai.values(), key=lambda q: (q['date'], q['conversation'])),
        by_ai=by_ai,
        conversations_by_start_month=dict(sorted(months.items())),
        conversations=sorted(rows, key=lambda r: (r['date'], r['id'])),
    )


